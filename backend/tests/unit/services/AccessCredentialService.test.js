const AccessCredentialService = require('../../../src/services/AccessCredentialService');
const InMemoryAccessCredentialRepository = require('../../../src/repositories/in-memory/InMemoryAccessCredentialRepository');
const InMemoryAuditLogRepository = require('../../../src/repositories/in-memory/InMemoryAuditLogRepository');
const InMemoryCandidateRepository = require('../../../src/repositories/in-memory/InMemoryCandidateRepository');
const { hashAccessCode } = require('../../../src/utils/accessCode');
const { PrintableService } = require('../../../src/services/PrintableService');
const { NotFoundError, ValidationError } = require('../../../src/utils/errors');

const PEPPER = 'secreto-de-prueba-con-32-caracteres!!';
const SESSION = {
  venue: 'Campus Central', room: 'Aula 204', startsAt: new Date('2026-11-05T14:00:00.000Z'), endsAt: new Date('2026-11-05T16:00:00.000Z'),
};
// End of 5 Nov 2026 in Guatemala.
const END_OF_DAY = new Date('2026-11-06T05:59:59.999Z');

describe('AccessCredentialService', () => {
  let credentialRepo;
  let auditRepo;
  let candidateRepo;
  let event;
  let clock;
  let service;
  let zoe;
  let ana;
  let bruno;

  beforeEach(async () => {
    credentialRepo = new InMemoryAccessCredentialRepository();
    auditRepo = new InMemoryAuditLogRepository();
    candidateRepo = new InMemoryCandidateRepository();
    const base = { eventId: 'event-1', orgId: 'org-1', status: 'CITED', cedula: '1' };
    zoe = await candidateRepo.create({ ...base, nombreCompleto: 'Zoe Ruiz' });
    ana = await candidateRepo.create({ ...base, nombreCompleto: 'Ána López' });
    bruno = await candidateRepo.create({ ...base, nombreCompleto: 'Bruno Díaz' });
    await candidateRepo.create({ ...base, orgId: 'org-2', nombreCompleto: 'Otra Empresa' });
    event = { id: 'event-1', orgId: 'org-1', modality: 'onsite', modules: ['A', 'B'], onsite: SESSION };
    clock = { now: new Date('2026-11-01T12:00:00.000Z') };
    service = new AccessCredentialService({
      credentialRepo,
      auditRepo,
      candidateRepo,
      eventService: {
        getEvent: jest.fn(async (eventId, orgId) => {
          if (orgId !== event.orgId) throw new NotFoundError('Evento no encontrado.');
          return event;
        }),
      },
      printableService: new PrintableService(),
      pepper: PEPPER,
      now: () => clock.now,
    });
  });

  const issueA = (ids, actor = 'user-1') => service.issueBatch('event-1', 'org-1', { module: 'A', candidateIds: ids }, actor);

  test('issues one code per candidate, returned once and stored only as an HMAC', async () => {
    const result = await issueA([zoe.id, ana.id, bruno.id]);

    // Alphabetical, for printing.
    expect(result.issued.map((item) => item.nombreCompleto)).toEqual(['Ána López', 'Bruno Díaz', 'Zoe Ruiz']);
    expect(result).toMatchObject({ module: 'A', skipped: [], rejected: [] });
    const [first] = result.issued;
    expect(first.code).toMatch(/^[A-Z2-9]{5}-[A-Z2-9]{5}$/);
    expect(first).toMatchObject({ module: 'A', expiresAt: END_OF_DAY, appointment: { venue: 'Campus Central', room: 'Aula 204' } });
    expect(new Set(result.issued.map((item) => item.code)).size).toBe(3);

    const stored = await credentialRepo.findById(first.credentialId);
    expect(stored).toMatchObject({
      orgId: 'org-1', eventId: 'event-1', candidateId: ana.id, module: 'A', status: 'GENERATED', expiresAt: END_OF_DAY, createdBy: 'user-1',
    });
    expect(stored.codeHash).toBe(hashAccessCode(first.code, PEPPER));
    expect(JSON.stringify(credentialRepo.data)).not.toContain(first.code);
    expect(JSON.stringify(credentialRepo.data)).not.toContain(first.code.replace('-', ''));
  });

  test('records who issued each credential, without codes', async () => {
    const result = await issueA([zoe.id]);
    expect(auditRepo.data).toEqual([expect.objectContaining({
      action: 'CREDENTIAL_ISSUED', actorUid: 'user-1', candidateId: zoe.id, credentialId: result.issued[0].credentialId, module: 'A', at: clock.now,
    })]);
    expect(JSON.stringify(auditRepo.data)).not.toContain(result.issued[0].code);
  });

  test('issuing again skips whoever already has a code: nothing is regenerated by accident', async () => {
    const first = await issueA([zoe.id, ana.id]);
    const again = await issueA([zoe.id, ana.id, bruno.id]);

    expect(again.issued.map((item) => item.nombreCompleto)).toEqual(['Bruno Díaz']);
    expect(again.skipped).toEqual([
      { candidateId: ana.id, nombreCompleto: 'Ána López', status: 'GENERATED' },
      { candidateId: zoe.id, nombreCompleto: 'Zoe Ruiz', status: 'GENERATED' },
    ]);
    expect(credentialRepo.data).toHaveLength(3);
    // The first codes still work.
    expect((await credentialRepo.findByCodeHash(hashAccessCode(first.issued[0].code, PEPPER))).status).toBe('GENERATED');
  });

  test('the summary shows each assignment state without revealing codes', async () => {
    await issueA([zoe.id, ana.id]);
    const summary = await service.summary('event-1', 'org-1');

    const moduleA = summary.modules.find((item) => item.module === 'A');
    expect(moduleA.rows.map((row) => [row.nombreCompleto, row.credential?.status ?? null])).toEqual([
      ['Ána López', 'GENERATED'], ['Bruno Díaz', null], ['Zoe Ruiz', 'GENERATED'],
    ]);
    expect(moduleA.counts).toMatchObject({ total: 3, prepared: 2, pending: 1, revoked: 0 });
    expect(JSON.stringify(summary)).not.toContain('codeHash');
    // Module B lists only candidates cited to it.
    expect(summary.modules.find((item) => item.module === 'B').rows).toEqual([]);
  });

  test('revoking stops a code and records who did it; reissuing gives a new code for the same assignment', async () => {
    const { issued: [old] } = await issueA([zoe.id]);

    const revoked = await service.revoke('event-1', 'org-1', old.credentialId, 'supervisor-1', 'Tarjeta extraviada');
    expect(revoked).toMatchObject({ status: 'REVOKED', revokedBy: 'supervisor-1', revokeReason: 'Tarjeta extraviada', revokedAt: clock.now });
    expect(revoked).not.toHaveProperty('codeHash');
    await expect(service.revoke('event-1', 'org-1', old.credentialId, 'supervisor-1')).rejects.toThrow('Solo se pueden revocar');

    // After revoking, the batch can issue again for that candidate.
    const fresh = await issueA([zoe.id]);
    expect(fresh.issued).toHaveLength(1);
    expect(fresh.issued[0].code).not.toBe(old.code);
    expect(auditRepo.data.map((entry) => entry.action)).toEqual(['CREDENTIAL_ISSUED', 'CREDENTIAL_REVOKED', 'CREDENTIAL_ISSUED']);
  });

  test('reissue revokes the current credential and issues its replacement in one step', async () => {
    const { issued: [old] } = await issueA([zoe.id]);
    const result = await service.reissue('event-1', 'org-1', old.credentialId, 'supervisor-1', 'Tarjeta dañada');

    const [replacement] = result.issued;
    expect(replacement.code).not.toBe(old.code);
    expect(await credentialRepo.findById(old.credentialId)).toMatchObject({
      status: 'REVOKED', revokedBy: 'supervisor-1', revokeReason: 'Tarjeta dañada', replacedById: replacement.credentialId,
    });
    expect(await credentialRepo.findById(replacement.credentialId)).toMatchObject({ status: 'GENERATED', replacesId: old.credentialId, createdBy: 'supervisor-1' });
    expect(auditRepo.data.slice(1).map((entry) => entry.action)).toEqual(['CREDENTIAL_REVOKED', 'CREDENTIAL_REISSUED']);

    // The replaced one cannot be reissued again (only the current one).
    await expect(service.reissue('event-1', 'org-1', old.credentialId, 'supervisor-1')).rejects.toThrow('ya fue reemplazada');
  });

  test('a used credential cannot be revoked or reissued', async () => {
    const { issued: [credential] } = await issueA([zoe.id]);
    await credentialRepo.update(credential.credentialId, () => ({ status: 'USED', usedAt: clock.now }));

    await expect(service.revoke('event-1', 'org-1', credential.credentialId, 'u')).rejects.toBeInstanceOf(ValidationError);
    await expect(service.reissue('event-1', 'org-1', credential.credentialId, 'u')).rejects.toThrow('ya se utilizó');
    expect((await issueA([zoe.id])).skipped).toEqual([expect.objectContaining({ status: 'USED' })]);
  });

  test('an unused credential reads as expired after its day, and can then be replaced', async () => {
    const { issued: [credential] } = await issueA([zoe.id]);
    clock.now = new Date('2026-11-06T06:00:00.000Z');

    const summary = await service.summary('event-1', 'org-1');
    expect(summary.modules[0].rows.find((row) => row.candidateId === zoe.id).credential.status).toBe('EXPIRED');
    await expect(service.revoke('event-1', 'org-1', credential.credentialId, 'u')).rejects.toBeInstanceOf(ValidationError);
    // The appointment day is over: no new codes either.
    expect((await issueA([zoe.id])).rejected).toEqual([expect.objectContaining({ reason: 'la jornada de su cita ya concluyó' })]);
  });

  test('candidates who cannot get a code are reported instead of failing the batch', async () => {
    await candidateRepo.update(ana.id, { status: 'EVALUATION_COMPLETED', submittedAt: new Date() });
    const result = await issueA([zoe.id, ana.id]);
    expect(result.issued.map((item) => item.candidateId)).toEqual([zoe.id]);
    expect(result.rejected).toEqual([{ candidateId: ana.id, nombreCompleto: 'Ána López', reason: 'ya completó el Módulo A' }]);
  });

  test('Module B codes use each candidate own Module B session', async () => {
    const sessionB = { venue: 'Campus Norte', room: 'Sala 3', startsAt: new Date('2026-11-20T15:00:00.000Z'), endsAt: new Date('2026-11-20T17:00:00.000Z') };
    await candidateRepo.update(zoe.id, { moduleB: { status: 'CITED', citation: { status: 'SENT', appointment: sessionB } } });

    const result = await service.issueBatch('event-1', 'org-1', { module: 'B', candidateIds: [zoe.id, ana.id] }, 'user-1');
    expect(result.issued).toEqual([expect.objectContaining({ candidateId: zoe.id, module: 'B', expiresAt: new Date('2026-11-21T05:59:59.999Z'), appointment: expect.objectContaining({ venue: 'Campus Norte' }) })]);
    expect(result.rejected).toEqual([expect.objectContaining({ candidateId: ana.id, reason: 'no tiene citación al Módulo B' })]);

    event = { ...event, modules: ['A'] };
    await expect(service.issueBatch('event-1', 'org-1', { module: 'B', candidateIds: [zoe.id] }, 'u'))
      .resolves.toMatchObject({ issued: [], rejected: [expect.objectContaining({ reason: 'Este evento no incluye el Módulo B.' })] });
  });

  test('regenerates the code if it happens to clash with an existing one', async () => {
    const codes = ['AAAAA-AAAAA', 'AAAAA-AAAAA', 'BBBBB-BBBBB'];
    service.generateCode = () => codes.shift();
    const result = await issueA([zoe.id, ana.id]);
    expect(result.issued.map((item) => item.code).sort()).toEqual(['AAAAA-AAAAA', 'BBBBB-BBBBB']);
  });

  describe('printable documents', () => {
    beforeEach(() => { event = { ...event, name: 'Concurso Presencial 2026' }; });

    test('the issuing response carries the cards PDF, built from the codes just issued', async () => {
      const printable = jest.spyOn(service.printableService, 'accessCards');
      const result = await service.issueBatch('event-1', 'org-1', { module: 'A', candidateIds: [zoe.id, ana.id], paper: 'A4' }, 'user-1');

      expect(result.cardsPdf).toMatchObject({ fileName: 'tarjetas-acceso-concurso-presencial-2026-modulo-a.pdf', contentType: 'application/pdf' });
      expect(Buffer.from(result.cardsPdf.base64, 'base64').subarray(0, 5).toString()).toBe('%PDF-');
      expect(printable).toHaveBeenCalledWith({ eventName: 'Concurso Presencial 2026', items: result.issued, paper: 'A4' });
      // Alphabetical cards, with no ID number.
      expect(printable.mock.calls[0][0].items.map((item) => item.nombreCompleto)).toEqual(['Ána López', 'Zoe Ruiz']);
      expect(JSON.stringify(printable.mock.calls[0][0].items)).not.toContain('cedula');
    });

    test('no PDF when nothing new was issued', async () => {
      await issueA([zoe.id]);
      expect(await issueA([zoe.id])).not.toHaveProperty('cardsPdf');
    });

    test('a reissued card comes with its own one-card PDF', async () => {
      const { issued: [old] } = await issueA([zoe.id]);
      const result = await service.reissue('event-1', 'org-1', old.credentialId, 'supervisor-1', 'Extraviada', 'CARTA');
      expect(result.cardsPdf.base64.length).toBeGreaterThan(100);
    });

    test('the attendance sheet lists the cited candidates alphabetically, without codes', async () => {
      await candidateRepo.update(zoe.id, { citation: { status: 'SENT' } });
      await candidateRepo.update(ana.id, { citation: { status: 'SENT' } });
      await candidateRepo.update(bruno.id, { citation: { status: 'FAILED' } });
      const printable = jest.spyOn(service.printableService, 'attendanceList');

      const { fileName, pdf } = await service.attendanceSheet('event-1', 'org-1', 'A', 'CARTA');

      expect(fileName).toBe('lista-asistencia-concurso-presencial-2026-modulo-a.pdf');
      expect(pdf.subarray(0, 5).toString()).toBe('%PDF-');
      const { rows, session } = printable.mock.calls[0][0];
      expect(rows.map((row) => [row.nombreCompleto, row.internalId])).toEqual([['Ána López', ana.id], ['Zoe Ruiz', zoe.id]]);
      expect(rows[0].appointmentAt).toEqual(SESSION.startsAt);
      expect(session).toBe(SESSION);
      expect(JSON.stringify(rows)).not.toMatch(/code|cedula/i);
    });

    test('the Module B sheet uses each candidate Module B session', async () => {
      const sessionB = { venue: 'Campus Norte', room: 'Sala 3', startsAt: new Date('2026-11-20T15:00:00.000Z'), endsAt: new Date('2026-11-20T17:00:00.000Z') };
      await candidateRepo.update(zoe.id, { moduleB: { status: 'CITED', citation: { status: 'SENT', appointment: sessionB } } });
      const printable = jest.spyOn(service.printableService, 'attendanceList');

      await service.attendanceSheet('event-1', 'org-1', 'B', 'CARTA');
      expect(printable.mock.calls[0][0]).toMatchObject({ module: 'B', session: sessionB, rows: [expect.objectContaining({ internalId: zoe.id, appointmentAt: sessionB.startsAt })] });

      event = { ...event, modules: ['A'] };
      await expect(service.attendanceSheet('event-1', 'org-1', 'B', 'CARTA')).rejects.toThrow('no incluye el Módulo B');
    });
  });

  describe('isolation and configuration', () => {
    test('another organization cannot see or act on the event credentials', async () => {
      const { issued: [credential] } = await issueA([zoe.id]);
      await expect(service.summary('event-1', 'org-2')).rejects.toBeInstanceOf(NotFoundError);
      await expect(service.issueBatch('event-1', 'org-2', { module: 'A', candidateIds: [zoe.id] }, 'x')).rejects.toBeInstanceOf(NotFoundError);
      await expect(service.revoke('event-1', 'org-2', credential.credentialId, 'x')).rejects.toBeInstanceOf(NotFoundError);
      await expect(service.reissue('event-1', 'org-2', credential.credentialId, 'x')).rejects.toBeInstanceOf(NotFoundError);
    });

    test('candidates of another event or organization cannot be included', async () => {
      const outsider = candidateRepo.data.find((candidate) => candidate.orgId === 'org-2');
      await expect(issueA([zoe.id, outsider.id])).rejects.toThrow('no pertenecen a este evento');
      expect(credentialRepo.data).toEqual([]);
    });

    test('only onsite events have access credentials', async () => {
      event = { ...event, modality: 'online' };
      await expect(issueA([zoe.id])).rejects.toThrow('presenciales');
    });

    test('without the server secret no code is issued', async () => {
      service.pepper = undefined;
      await expect(issueA([zoe.id])).rejects.toThrow('ACCESS_CODE_PEPPER');
      expect(credentialRepo.data).toEqual([]);
    });
  });
});
