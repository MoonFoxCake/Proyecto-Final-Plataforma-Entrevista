import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import { AuthContext } from '../context/AuthContext.jsx';
import { AdminAccountsPage } from './AdminAccountsPage.jsx';
import { AdminAccountEditor } from '../components/admin/AdminAccountEditor.jsx';
import { AccountPasswordDialog } from '../components/admin/AccountPasswordDialog.jsx';
import { AdminSidebar } from '../components/admin/AdminSidebar.jsx';
import { RequirePermission } from '../router/RequirePermission.jsx';
import { canSection } from '../utils/adminPermissions.js';
import * as api from '../services/adminAccountsApi.js';
import { changePassword } from '../services/authService.js';
vi.mock('../services/adminAccountsApi.js', () => ({ listAdminAccounts: vi.fn(), listUserAccounts: vi.fn(), createAdminAccount: vi.fn(), updateAdminAccount: vi.fn(), setAdminStatus: vi.fn(), resetAdminPassword: vi.fn(), deleteAccount: vi.fn() }));
vi.mock('../services/authService.js', () => ({ changePassword: vi.fn(), logout: vi.fn() }));
vi.mock('../services/adminReviewService.js', () => ({ getProcesses: vi.fn(async () => []) }));
const owner = { id: 'owner', role: 'admin', adminAccess: 'owner', username: 'owner', displayName: 'Propietario', status: 'active', permissions: [], revision: 1 };
const evaluator = { id: 'reviewer', role: 'admin', adminAccess: 'restricted', username: 'reviewer', displayName: 'Ana Evaluadora', status: 'active', permissions: ['processes.view', 'evaluations.review'], revision: 1 };
const wrap = (child, profile = owner) => <MemoryRouter><AuthContext.Provider value={{ profile, user: profile, role: profile.role, loading: false }}>{child}</AuthContext.Provider></MemoryRouter>;
beforeAll(() => { HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); }; });
beforeEach(() => {
  vi.resetAllMocks();
  api.listAdminAccounts.mockResolvedValue([owner, evaluator]);
  api.listUserAccounts.mockResolvedValue([]);
  api.createAdminAccount.mockResolvedValue({ account: { ...evaluator, id: 'new', username: 'maria', displayName: 'María Nueva' }, temporaryPassword: 'temporary-password-only-once' });
  api.deleteAccount.mockResolvedValue({ deleted: true });
});
afterEach(cleanup);
test('sidebar exposes only authorized sections for restricted accounts and fails closed for legacy admins', () => {
  const { unmount } = render(wrap(<AdminSidebar activeSection="results" onSelect={() => {}} />, evaluator));
  const nav = within(screen.getByRole('navigation'));
  // Saved with the old ids, the account keeps its access under Resultados.
  expect(nav.getByRole('button', { name: /Resultados/ })).toBeTruthy();
  expect(nav.queryByRole('button', { name: /Procesos|Empresas|Accesos|Preguntas|Macrocasos|Microcasos/ })).toBeNull();
  unmount();
  expect(canSection({ role: 'admin' }, 'dashboard')).toBe(false);
  expect(canSection({ ...owner, status: 'disabled' }, 'accounts')).toBe(false);
});
test('protects direct routes even when menu navigation is bypassed', () => {
  render(wrap(<Routes><Route element={<RequirePermission permissions={['questions.manage']} />}><Route index element={<div>SECRET CONTENT</div>} /></Route></Routes>, evaluator));
  expect(screen.getByRole('heading', { name: 'Acceso restringido' })).toBeTruthy();
  expect(screen.queryByText('SECRET CONTENT')).toBeNull();
});
test('restricted creators cannot select full access, unknown grants or templates beyond their permissions', async () => {
  const actor = { ...evaluator, permissions: ['results.view', 'results.deliver', 'admins.create'] };
  const save = vi.fn().mockResolvedValue(undefined);
  render(wrap(<AdminAccountEditor actor={actor} onSave={save} onClose={() => {}} />, actor));
  expect(screen.getByRole('radio', { name: /Control total/ }).disabled).toBe(true);
  expect(screen.getByRole('button', { name: 'Gestor de contenido' }).disabled).toBe(true);
  const enabled = screen.getAllByRole('checkbox').filter((box) => !box.disabled);
  expect(enabled).toHaveLength(3);
  fireEvent.change(screen.getByLabelText('Nombre de la persona'), { target: { value: 'María Nueva' } });
  fireEvent.change(screen.getByLabelText('Nombre de usuario'), { target: { value: 'maria' } });
  fireEvent.click(screen.getByRole('button', { name: 'Evaluador' }));
  fireEvent.click(screen.getByRole('button', { name: 'Crear cuenta' }));
  await waitFor(() => expect(save).toHaveBeenCalledWith({ displayName: 'María Nueva', username: 'maria', adminAccess: 'restricted', permissions: ['results.view', 'results.deliver'] }));
});
test('creates accounts and shows the temporary password only until the credentials dialog closes', async () => {
  render(wrap(<AdminAccountsPage />));
  await screen.findByRole('article', { name: 'Ana Evaluadora' });
  const protectedRow = within(screen.getByRole('article', { name: 'Propietario' }));
  expect(protectedRow.queryByRole('button', { name: /Eliminar|Editar|Desactivar|Restablecer/ })).toBeNull();
  fireEvent.click(screen.getByRole('button', { name: '+ Nuevo administrador' }));
  fireEvent.change(screen.getByLabelText('Nombre de la persona'), { target: { value: 'María Nueva' } });
  fireEvent.change(screen.getByLabelText('Nombre de usuario'), { target: { value: 'maria' } });
  fireEvent.click(screen.getByRole('button', { name: 'Crear cuenta' }));
  expect(await screen.findByText('temporary-password-only-once')).toBeTruthy();
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cerrar', exact: true }));
  expect(screen.queryByText('temporary-password-only-once')).toBeNull();
  expect(screen.getByRole('article', { name: 'María Nueva' })).toBeTruthy();
});
test('requires typed confirmation before account deletion', async () => {
  render(wrap(<AdminAccountsPage />));
  const row = await screen.findByRole('article', { name: 'Ana Evaluadora' });
  fireEvent.click(within(row).getByRole('button', { name: 'Eliminar cuenta' }));
  expect(screen.getByRole('button', { name: 'Confirmar' }).disabled).toBe(true);
  fireEvent.change(screen.getByLabelText('Escribe reviewer para confirmar'), { target: { value: 'reviewer' } });
  fireEvent.click(screen.getByRole('button', { name: 'Confirmar' }));
  await waitFor(() => expect(api.deleteAccount).toHaveBeenCalledWith(evaluator, 'reviewer'));
  await waitFor(() => expect(screen.queryByRole('article', { name: 'Ana Evaluadora' })).toBeNull());
});
test('uses refreshed revisions to retry a failed deletion', async () => {
  api.deleteAccount.mockRejectedValueOnce(new Error('Provider unavailable'));
  render(wrap(<AdminAccountsPage />));
  const row = await screen.findByRole('article', { name: 'Ana Evaluadora' });
  api.listAdminAccounts.mockResolvedValue([owner, { ...evaluator, status: 'deletion_pending', revision: 2 }]);
  fireEvent.click(within(row).getByRole('button', { name: 'Eliminar cuenta' }));
  fireEvent.change(screen.getByLabelText('Escribe reviewer para confirmar'), { target: { value: 'reviewer' } });
  fireEvent.click(screen.getByRole('button', { name: 'Confirmar' }));
  await screen.findByRole('alert');
  await waitFor(() => expect(screen.getByRole('button', { name: 'Confirmar' }).disabled).toBe(false));
  fireEvent.click(screen.getByRole('button', { name: 'Confirmar' }));
  await waitFor(() => expect(api.deleteAccount).toHaveBeenLastCalledWith(expect.objectContaining({ revision: 2, status: 'deletion_pending' }), 'reviewer'));
});
test('user-only administrators do not request or display the administrators directory', async () => {
  render(wrap(<AdminAccountsPage />, { ...evaluator, permissions: ['users.view'] }));
  await screen.findByText('No hay cuentas que coincidan con los filtros.');
  expect(api.listAdminAccounts).not.toHaveBeenCalled();
  expect(api.listUserAccounts).toHaveBeenCalledOnce();
  expect(screen.queryByRole('button', { name: '+ Nuevo administrador' })).toBeNull();
});
test('changing own password requires matching confirmation and clears credentials after success', async () => {
  changePassword.mockResolvedValue(undefined);
  render(wrap(<AccountPasswordDialog onClose={() => {}} />));
  fireEvent.change(screen.getByLabelText('Contraseña actual'), { target: { value: 'previous-password' } });
  fireEvent.change(screen.getByLabelText('Nueva contraseña'), { target: { value: 'new-password-long' } });
  fireEvent.click(screen.getByRole('button', { name: 'Cambiar contraseña' }));
  expect(changePassword).not.toHaveBeenCalled();
  fireEvent.change(screen.getByLabelText('Confirmar nueva contraseña'), { target: { value: 'new-password-long' } });
  fireEvent.click(screen.getByRole('button', { name: 'Cambiar contraseña' }));
  await screen.findByText('Contraseña actualizada correctamente.');
  expect(changePassword).toHaveBeenCalledWith('previous-password', 'new-password-long');
  expect(screen.queryByLabelText('Contraseña actual')).toBeNull();
});
